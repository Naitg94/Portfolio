import asyncio
import re
from playwright import async_api
from playwright.async_api import expect

async def run_test():
    pw = None
    browser = None
    context = None

    try:
        # Start a Playwright session in asynchronous mode
        pw = await async_api.async_playwright().start()

        # Launch a Chromium browser in headless mode with custom arguments
        browser = await pw.chromium.launch(
            headless=True,
            args=[
                "--window-size=1280,720",
                "--disable-dev-shm-usage",
                "--ipc=host",
                "--single-process"
            ],
        )

        # Create a new browser context (like an incognito window)
        context = await browser.new_context()
        # Wider default timeout to match the agent's DOM-stability budget;
        # auto-waiting Playwright APIs (expect, locator.wait_for) inherit this.
        context.set_default_timeout(15000)

        # Open a new page in the browser context
        page = await context.new_page()

        # Interact with the page elements to simulate user flow
        # -> navigate
        await page.goto("http://localhost:4173")
        try:
            await page.wait_for_load_state("domcontentloaded", timeout=5000)
        except Exception:
            pass
        
        # -> Click the 'RESUME' button in the top navigation to trigger the resume download.
        # Download: RESUME link
        elem = page.get_by_role('link', name='RESUME', exact=True)
        async with page.expect_download(timeout=30000) as dl_info:
            await elem.click(timeout=10000)
        download = await dl_info.value
        assert download.suggested_filename  # verify file was downloaded
        await download.save_as(f"./downloads/{download.suggested_filename}")
        
        # -> Click the 'RESUME' button in the top navigation to start the resume download and verify the download behavior.
        # Download: RESUME link
        elem = page.get_by_role('link', name='RESUME', exact=True)
        async with page.expect_download(timeout=30000) as dl_info:
            await elem.click(timeout=10000)
        download = await dl_info.value
        assert download.suggested_filename  # verify file was downloaded
        await download.save_as(f"./downloads/{download.suggested_filename}")
        
        # -> Click the 'RESUME' link in the top navigation and verify the resume download is initiated (confirm link target /Naitik_Goyal_Resume.pdf).
        # Download: RESUME link
        elem = page.get_by_role('link', name='RESUME', exact=True)
        async with page.expect_download(timeout=30000) as dl_info:
            await elem.click(timeout=10000)
        download = await dl_info.value
        assert download.suggested_filename  # verify file was downloaded
        await download.save_as(f"./downloads/{download.suggested_filename}")
        
        # -> Click the 'RESUME' button in the top navigation after confirming the anchor href targets the resume PDF.
        # Download: RESUME link
        elem = page.get_by_role('link', name='RESUME', exact=True)
        async with page.expect_download(timeout=30000) as dl_info:
            await elem.click(timeout=10000)
        download = await dl_info.value
        assert download.suggested_filename  # verify file was downloaded
        await download.save_as(f"./downloads/{download.suggested_filename}")
        
        # -> Collect the visible text and href attributes of all links on the page.
        # Download: RESUME link
        elem = page.get_by_role('link', name='RESUME', exact=True)
        async with page.expect_download(timeout=30000) as dl_info:
            await elem.click(timeout=10000)
        download = await dl_info.value
        assert download.suggested_filename  # verify file was downloaded
        await download.save_as(f"./downloads/{download.suggested_filename}")
        
        # --> Assertions to verify final state
        
        # --> The top-navigation RESUME link targets the resume PDF at /Naitik_Goyal_Resume.pdf.
        # Assert-outcome: passed
        # Assert: Top-navigation RESUME link href is the resume PDF URL.
        await expect(page.locator("xpath=/html/body/div/div/header/nav/div[2]/a").nth(0)).to_have_attribute("href", "http://localhost:4173/Naitik_Goyal_Resume.pdf", timeout=15000), "Top-navigation RESUME link href is the resume PDF URL."
        await asyncio.sleep(5)

    finally:
        if context:
            await context.close()
        if browser:
            await browser.close()
        if pw:
            await pw.stop()

asyncio.run(run_test())
    